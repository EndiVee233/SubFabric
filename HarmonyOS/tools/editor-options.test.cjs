const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require(path.join(process.env.DEVECO_HOME || 'D:/HarmonyOS/DevEcoStudio',
  'sdk/default/openharmony/ets/build-tools/ets-loader/node_modules/typescript/lib/typescript.js'));
const root = path.resolve(__dirname, '..');
const cache = new Map();
let common;
function load(file) {
  file = path.resolve(file);
  if (cache.has(file)) return cache.get(file);
  const out = {};
  cache.set(file, out);
  const js = ts.transpile(fs.readFileSync(file, 'utf8'), { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 });
  new Function('require', 'exports', js)(name => name === 'common' ? common : load(path.resolve(path.dirname(file), name + '.ets')), out);
  return out;
}
common = Object.assign({}, load(root + '/common/src/main/ets/model/Cue.ets'),
  load(root + '/common/src/main/ets/util/TimeUtil.ets'), load(root + '/common/src/main/ets/subtitle/SubtitleIo.ets'));
const api = load(root + '/entry/src/main/ets/ui/editor/EditorOptions.ets');
const o = api.defaultEditorOptions();
const cue = new common.Cue(1, 1, 3, '[Alice] Hello world', '[Alice] 你好世界');
cue.speaker = 'Alice'; cue.speakerColor = '#FF0000';
cue.words = [new common.WordTiming('Hello', 1, 1.8), new common.WordTiming('world', 1.9, 2.8)];
const initial = JSON.stringify(cue);
o['zh.Fontname'] = 'Example Font'; o['zh.Fontsize'] = '66'; o['en.Italic'] = '1';
let ass = api.buildEditorAss([cue], o);
assert(ass.includes('Style: Main,Example Font,66,'));
assert(ass.includes('Style: Sub,HarmonyOS Sans SC,34,'));
assert(ass.includes('你好世界'));
assert(!ass.includes('[Alice]'));
assert(ass.includes('Sub,Alice,'));
assert(ass.includes('\\c&H0000FF&'), 'role RGB red must become ASS BGR red');
assert(ass.includes('Hello') && ass.includes('world'));
assert(!api.buildEditorAss([cue], o, 'zh').includes('Hello'));
assert(!api.buildEditorAss([cue], o, 'en').includes('你好世界'));
const clean = api.buildEditorAss([cue], o, 'clean');
assert.equal((clean.match(/^Dialogue:/gm) || []).length, 2);
o['fx.enabled'] = '1'; o['fx.glow.target'] = 'all'; o['fx.glow.zh.channel'] = 'shadow';
o['fx.fadein.enabled'] = '1'; o['fx.fadein.target'] = 'zh';
ass = api.buildEditorAss([cue], o);
assert(ass.includes('\\4c&H88FF00&'));
assert(ass.includes('\\fade('));
assert(!ass.includes('\\t(') && !ass.includes('\\bord'), 'effects must not introduce collision-unsafe transforms or change borders');
assert.equal(JSON.stringify(cue), initial, 'export must not modify editor data');
o['karaokeMode'] = 'karaoke'; o['kSweep'] = '1';
ass = api.buildEditorAss([cue], o);
assert(ass.includes('\\kf80'));
assert(ass.includes('\\k10'), 'keep gap between timed words');
const preset = api.makeEditorPreset(o, 'Bilingual Glow');
assert.equal(preset.kind, 'subfabric.subtitle-style-preset');
const restored = api.applyEditorPreset(api.defaultEditorOptions(), JSON.parse(JSON.stringify(preset)));
assert.equal(restored['zh.Fontname'], 'Example Font');
assert.equal(restored['fx.glow.target'], 'all');
assert.equal(restored['kSweep'], '1');
const legacy = api.makeEditorPreset(o, 'Legacy', true);
legacy.tracks.zh.format.reverse(); legacy.tracks.zh.values.reverse();
const imported = api.applyEditorPreset(api.defaultEditorOptions(), legacy);
assert.equal(imported['zh.Fontsize'], '66', 'match track values by format name, never field position');
assert.equal(imported['fx.enabled'], '0', 'pure style import must not turn on effects');
assert.throws(() => api.applyEditorPreset(o, { kind: 'not-a-subfabric-preset' }));
const normalized = api.normalizeEditorOptions(Object.assign({}, o, { 'zh.Fontsize': '9999', 'wordColor': 'bad', 'fx.fadein.duration': '-1' }));
assert.equal(normalized['zh.Fontsize'], '200');
assert.equal(normalized['wordColor'], '#00FF00');
assert.equal(normalized['fx.fadein.duration'], '40');
console.log('Editor settings: ASS languages, styles, role colors, karaoke, effects, immutable export, new/legacy preset round-trip and validation passed.');
