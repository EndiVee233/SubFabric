import assert from 'node:assert/strict';
const calls=[];
globalThis.window={androidStudio:{rpc:async(action,arg)=>{calls.push({action,arg});if(action==='downloadStatus')return {id:arg.id,status:'done',result:{source:{title:'actual'},hasThumbnail:true}};if(action==='studioCreate')return {id:'new'};return {ok:true};}}};
window.androidStudio.create=async(name,text,subtitleName)=>{calls.push({action:'studioCreate',arg:{name,text,subtitleName}});return {id:'new'};};
window.androidStudio.update=async(id,patch)=>{calls.push({action:'studioUpdate',arg:{id,patch}});return {};};
const download=await import('../android/app/src/main/assets/studio/android-download.js');
const result=await download.finish({id:'job',status:'running'});
assert.equal(result.source.thumbnail,'/api/downloads/job/thumbnail');
await assert.rejects(()=>download.finish({status:'interrupted',error:'process stopped'}),/process stopped/);
const controller=new AbortController();controller.abort();
await assert.rejects(()=>download.finish({id:'cancel',status:'running'},controller.signal),/取消/);
assert.deepEqual(calls.at(-1),{action:'downloadCancel',arg:{id:'cancel'}});
await download.route('/api/fetch/settings','POST',{youtubeCookies:'isolated-test'});
assert.equal(calls.at(-1).action,'downloadSettings');
const id=await download.attach({mediaId:'media',mediaName:'video.mp4',source:{title:'download'}},'existing');
assert.equal(id,'existing');assert.equal(calls.at(-1).arg.id,'existing');
assert.equal(calls.at(-1).arg.patch.mediaId,'media');assert.equal('text' in calls.at(-1).arg.patch,false,'Media association must preserve original subtitles');
assert.equal(await download.attach({mediaId:'media',mediaName:'video.mp4',source:{title:'download'}}),'new');
assert.match(calls.find(c=>c.action==='studioCreate').arg.text,/\[Events\]/);
console.log('Android download API completion, cancellation and media association preserve subtitle contents');
