/** 验证时间轴载入时默认显示 30 秒；短视频按实际时长显示。 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = fs.readFileSync(path.join(HERE, '..', 'editor', 'js', 'timeline.js'), 'utf8');
let pass = 0, fail = 0;
const ok = (cond, name, extra) => { if (cond) { pass++; console.log('  ok  ' + name); } else { fail++; console.log('FAIL  ' + name + (extra === undefined ? '' : ' :: ' + extra)); } };
const DEFAULT_SPAN = 30, W = 1200;
const contentRange = (duration, subEnd) => { const end = Math.max(duration || 0, subEnd || 0); return end > 0 ? { a: 0, b: end, span: end } : null; };
function applyDefaultView({ duration, subEnd, w }) {
  const r = contentRange(duration, subEnd); if (!r || w <= 0) return null;
  return { mode: 'default', pxPerSec: w / Math.max(0.2, Math.min(DEFAULT_SPAN, r.span)), viewStart: r.a };
}
const visibleSpan = r => W / r.pxPerSec;
console.log('== 长稿子：默认只看 30 秒 ==');
let r = applyDefaultView({ duration: 3428, subEnd: 3416, w: W });
ok(r.mode === 'default', '走默认视图', r.mode);
ok(r.viewStart === 0, '视图从 0 开始', r.viewStart);
ok(Math.abs(visibleSpan(r) - 30) < 1e-6, '可见范围为 30s', visibleSpan(r));
console.log('\n== 236 秒视频 ==');
r = applyDefaultView({ duration: 236, subEnd: 228.5, w: W });
ok(r.mode === 'default', '走默认视图', r.mode);
ok(Math.abs(visibleSpan(r) - 30) < 1e-6, '可见范围为 30s', visibleSpan(r));
console.log('\n== 很短的稿子（< 30s）==');
r = applyDefaultView({ duration: 12, subEnd: 12, w: W });
ok(r.mode === 'default', '走默认', r.mode);
ok(Math.abs(r.pxPerSec - W / 12) < 1e-9, '跨度取 min(30, 12) = 12', r.pxPerSec);
console.log('\n== 边界与健壮性 ==');
r = applyDefaultView({ duration: 0, subEnd: 228.5, w: W });
ok(r && r.mode === 'default', '视频时长未知但字幕有范围 -> 仍按 30s 默认', r && r.mode);
ok(Math.abs(visibleSpan(r) - 30) < 1e-6, '未知视频时长仍以 30s 为默认跨度', visibleSpan(r));
ok(applyDefaultView({ duration: 0, subEnd: 0, w: W }) === null, '完全没有范围 -> 不动视图');
ok(applyDefaultView({ duration: 236, subEnd: 0, w: 0 }) === null, '宽度为 0 -> 不动视图');
r = applyDefaultView({ duration: 30, subEnd: 30, w: W });
ok(r.mode === 'default', '恰好 30s -> 走默认', r.mode);
console.log('\n== 源码关键点仍在（防回退）==');
const resetDef = SRC.lastIndexOf('resetView() {');
const defDef = SRC.lastIndexOf('_applyDefaultView() {');
ok(resetDef > 0 && defDef > resetDef, 'resetView 与默认视图方法仍存在');
ok(!SRC.includes('_fitOnLoad'), '默认载入不再强制 fit 全片');
ok(/const DEFAULT_SPAN = 30/.test(SRC), 'DEFAULT_SPAN 仍是 30');
ok(!/tick\(\)[\s\S]{0,200}?this\.fit\(\)/.test(SRC), 'fit 没有被放进每帧循环');
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
