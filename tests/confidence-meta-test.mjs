/**
 * 置信度元数据的写入↔读取往返测试。
 *
 * 前后端之间只有这一条接口：server.js 把置信度写进 ASS 的 Script Info 注释，
 * 前端从注释里解析回来。两边都不依赖模型，所以可以单独测——这比跑整条
 * 初稿流水线（要 ASR + LLM）快得多，也能覆盖格式边界。
 *
 *   node tests/confidence-meta-test.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.dirname(HERE);

let pass = 0, fail = 0;
const ok = (cond, name, extra) => {
  if (cond) { pass++; console.log('  ok  ' + name); }
  else { fail++; console.log('FAIL  ' + name + (extra === undefined ? '' : ' :: ' + JSON.stringify(extra))); }
};

/* ── 从 server.js 里取出这两个纯函数（避免为了测试去起整个服务器）── */
const serverSrc = fs.readFileSync(path.join(REPO, 'editor', 'server.js'), 'utf8');
const grab = (name) => {
  const i = serverSrc.indexOf('function ' + name + '(');
  if (i < 0) throw new Error('server.js 里找不到 ' + name);
  // 从函数头开始做花括号配平
  let depth = 0, started = false;
  for (let j = i; j < serverSrc.length; j++) {
    if (serverSrc[j] === '{') { depth++; started = true; }
    else if (serverSrc[j] === '}') { depth--; if (started && depth === 0) return serverSrc.slice(i, j + 1); }
  }
  throw new Error(name + ' 括号不配平');
};
const confidenceMeta = eval('(' + grab('confidenceMeta') + ')');
const withConfidence = eval('(' + grab('withConfidence') + ')');

/* ── 从 ass.js 里取 AssDoc（前端解析用的就是它）── */
// Windows 绝对路径必须转成 file:// URL 才能动态 import（否则报 ERR_UNSUPPORTED_ESM_URL_SCHEME）
const { AssDoc } = await import(pathToFileURL(path.join(REPO, 'editor', 'js', 'ass.js')).href);

const header = `[Script Info]
; Generated by K-ASS-Editor draft (test)
ScriptType: v4.00+
PlayResX: 1920

[V4+ Styles]
Format: Name, Fontname, Fontsize
Style: Default,Arial,65

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:00:00.00,0:00:02.00,Default,,0,0,0,,hello world
Dialogue: 0,0:00:02.00,0:00:04.00,Default,,0,0,0,,second line
`;

console.log('== 写入 ==');
const segs = [
  { start: 0, end: 2, text: 'hello world', confidence: { score: 0.91, low: false, worstWord: 1 } },
  { start: 2, end: 4, text: 'second line', confidence: { score: 0.42, low: true, worstWord: 0 } },
];
const meta = confidenceMeta(segs);
console.log('   meta =', JSON.stringify(meta));
ok(meta === '0:0.91:1,1:0.42:0', '格式为 行号:分数:最差词', meta);

const withMeta = withConfidence(header, segs);
ok(withMeta.includes('; SubFabricConfidence: 0:0.91:1,1:0.42:0'), '注释写进了 ASS');
ok(withMeta.indexOf('SubFabricConfidence') > withMeta.indexOf('[Script Info]')
  && withMeta.indexOf('SubFabricConfidence') < withMeta.indexOf('[V4+ Styles]'),
  '注释落在 Script Info 段内（播放器会忽略的位置）');
ok(withMeta.split('\n').length === header.split('\n').length + 1, '只多了一行');

console.log('\n== 没有置信度数据时不该乱写 ==');
ok(confidenceMeta([{ start: 0, end: 1, text: 'x' }]) === '', '没有 confidence 字段 → 空串');
ok(confidenceMeta([]) === '', '空列表 → 空串');
ok(withConfidence(header, [{ start: 0, end: 1, text: 'x' }]) === header, '无数据时原样返回');
ok(confidenceMeta([{ confidence: { score: NaN } }]) === '', 'NaN 分数被跳过');
ok(confidenceMeta([{ confidence: { score: 2 } }]) === '0:1.00:', '越界分数被夹到 1.00');

console.log('\n== 读取（前端路径）==');
const doc = new AssDoc(withMeta);
const raw = doc.getScriptInfoComment('SubFabricConfidence');
console.log('   读回 =', JSON.stringify(raw));
ok(raw === '0:0.91:1,1:0.42:0', 'AssDoc 能读回原文');
ok(withMeta.includes('Dialogue: 0,0:00:00.00,0:00:02.00,Default,,0,0,0,,hello world'),
  '原有 Dialogue 行没被破坏');
ok(new AssDoc(withMeta).events.length === new AssDoc(header).events.length,
  '事件数与加注释前一致（注释不被当成事件）');

console.log('\n== 解析容错（前端 parseConfidenceMeta 的口径）==');
const LOW = 0.62;
const parse = (s) => {
  const out = new Map();
  for (const piece of String(s).split(',')) {
    const f = piece.split(':');
    if (f.length < 2) continue;
    const idx = parseInt(f[0], 10), score = parseFloat(f[1]);
    if (!Number.isInteger(idx) || idx < 0 || !Number.isFinite(score)) continue;
    const w = parseInt(f[2], 10);
    out.set(idx, { score: Math.max(0, Math.min(1, score)), low: score < LOW,
      worstWord: Number.isInteger(w) && w >= 0 ? w : null });
  }
  return out;
};
ok(parse('0:0.91:1,1:0.42:0').get(1).low === true, '0.42 判为低置信度');
ok(parse('0:0.91:1,1:0.42:0').get(0).low === false, '0.91 判为正常');
ok(parse('0:0.91:1,1:0.42:0').get(1).worstWord === 0, '最差词下标解析正确');
ok(parse('garbage').size === 0, '垃圾串 → 空（不抛异常）');
ok(parse('0:abc,1:0.5').get(1).score === 0.5, '坏行跳过、好行保留');
ok(parse('0:0.5:').get(0).worstWord === null, '缺最差词下标 → null');
ok(parse('5:0.9:0').get(5) !== undefined, '行号允许比实际行数大（越界由调用方忽略）');

console.log(`\n${fail ? `FAILED (${fail})` : 'ALL OK'}  —  ${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
